import { chromium } from "playwright";
import fs from "fs";
const SP = fs.readFileSync(".sp.tmp","utf8").trim();
const B = "http://localhost:3100";
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 375, height: 800 } });
const p = await ctx.newPage();
p.on("pageerror", (e) => console.log("PAGEERR:", e.message.slice(0, 300)));
p.on("console", (m) => { if (m.type() === "error") console.log("CONSOLE:", m.text().slice(0, 200)); });
const shot = (n, full = false) => p.screenshot({ path: `${SP}/${n}.png`, fullPage: full });
async function login(who) {
  await ctx.clearCookies();
  await p.goto(B + "/login", { waitUntil: "networkidle" });
  await p.getByTestId("demo-" + who).click();
  await p.waitForURL(/board|admin/);
  await p.waitForLoadState("networkidle");
}
await login("alice");
await p.goto(B + "/items/22222222-aaaa-4aaa-8aaa-0000000a0413", { waitUntil: "networkidle" });
await p.getByTestId("claim-start").click();
await p.waitForURL(/claim\//);
const claimId = p.url().split("/claim/")[1];
await p.getByTestId("claim-prompt-1").waitFor();
const ans = ["A red royal enfield bike", "a folded 100 rupee note", "cat sticker"];
for (let i = 0; i < 3; i++) await p.getByTestId(`claim-prompt-${i+1}`).fill(ans[i]);
await p.getByTestId("claim-submit").click();
await p.waitForTimeout(500); await shot("alice-t500");
await p.waitForTimeout(700); await shot("alice-t1200");
await p.getByTestId("claim-result").waitFor({ timeout: 8000 });
await p.waitForTimeout(1200); await shot("alice-result", true);
console.log("score:", await p.getByTestId("trust-score").innerText());
console.log("qr visible:", await p.getByTestId("claim-qr").isVisible());
const token = await p.evaluate((id) => { const d = JSON.parse(sessionStorage.getItem("tt-mock-db")); return d.claims.find(c => c.id === id).token; }, claimId);
await login("admin");
await p.setViewportSize({ width: 1280, height: 800 });
await p.goto(B + "/admin", { waitUntil: "networkidle" }); await shot("admin-dash");
await p.goto(B + "/admin/claims", { waitUntil: "networkidle" });
await p.getByTestId("claim-row").first().click(); await p.waitForTimeout(500); await shot("admin-claims");
await p.goto(B + "/admin/scan", { waitUntil: "networkidle" });
await p.getByTestId("scan-manual").click();
await p.getByTestId("scan-code").fill(token);
await p.getByTestId("scan-check").click();
await p.getByTestId("scan-result").waitFor();
console.log("scan ok:", await p.getByTestId("scan-result").getAttribute("data-ok")); await shot("admin-scan");
await p.getByTestId("scan-again").click();
await p.getByTestId("scan-code").fill(token); await p.getByTestId("scan-check").click();
await p.waitForTimeout(400);
console.log("second scan:", (await p.getByTestId("scan-result").innerText()).split("\n")[0]);
await p.setViewportSize({ width: 375, height: 800 });
await login("alice");
await p.goto(B + "/thanks/" + claimId, { waitUntil: "networkidle" });
await p.getByTestId("tip-amount-50").click(); await shot("thanks");
await p.getByTestId("tip-send").click();
await p.getByTestId("tip-done").waitFor(); await shot("thanks-done");
await p.goto(B + "/heroes", { waitUntil: "networkidle" }); await shot("heroes");
await p.goto(B + "/notifications", { waitUntil: "networkidle" }); await shot("notifs");
await p.goto(B + "/me", { waitUntil: "networkidle" }); await shot("me", true);
await b.close();
